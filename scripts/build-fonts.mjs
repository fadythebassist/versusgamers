// Builds self-hosted, per-skin font CSS from @fontsource packages:
//   public/fonts/<skin>.css   (@font-face rules for that skin only, latin + latin-ext)
//   public/fonts/files/*.woff2
// The page loads only the active skin's CSS, so visitors download only the fonts they see.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { SKINS } from '../src/config/skins.mjs';

const OUT = 'public/fonts';
mkdirSync(join(OUT, 'files'), { recursive: true });
const KEEP = /-(latin|latin-ext)-\d+-normal \*\//;
let copied = 0;

for (const skin of SKINS) {
  let css = `/* ${skin.id} skin fonts — generated by scripts/build-fonts.mjs */\n`;
  for (const [pkg, weights] of skin.fonts) {
    const dir = join('node_modules', '@fontsource', pkg);
    for (const w of weights) {
      const file = join(dir, `${w}.css`);
      if (!existsSync(file)) throw new Error(`Missing ${file}`);
      const blocks = readFileSync(file, 'utf8').split(/(?=\/\* )/);
      for (const block of blocks) {
        if (!KEEP.test(block)) continue;
        const out = block.replace(/src: url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\)(, url\([^)]+\) format\('woff'\))?/, (_, f) => {
          const dest = join(OUT, 'files', f);
          if (!existsSync(dest)) { copyFileSync(join(dir, 'files', f), dest); copied++; }
          return `src: url(/fonts/files/${f}) format('woff2')`;
        });
        css += out.trimEnd() + '\n\n';
      }
    }
  }
  writeFileSync(join(OUT, `${skin.id}.css`), css);
}
console.log(`fonts: ${SKINS.length} skin stylesheets, ${copied} new font files`);
