// Generates src/styles/skins.css from src/config/skins.mjs.
// Run with `npm run gen` (also runs automatically before `npm run build`).
import { writeFileSync, mkdirSync } from 'node:fs';
import { SKINS, DEFAULT_SKIN, HERO_VARIANTS } from '../src/config/skins.mjs';

const q = (s) => JSON.stringify(s); // CSS string literal

function vars(t) {
  const v = {
    '--bg': t.bg, '--surface': t.surface, '--hero-bg': t.heroBg, '--border': t.border, '--border-strong': t.borderStrong,
    '--bw': t.borderW, '--text': t.text, '--body': t.body, '--muted': t.muted,
    '--accent': t.accent, '--on-accent': t.onAccent, '--accent2': t.accent2, '--on-accent2': t.onAccent2,
    '--kicker': t.kicker, '--link': t.link, '--logo1': t.logo1, '--logo2': t.logo2, '--h2-color': t.h2Color,
    '--f-display': t.fontDisplay, '--f-label': t.fontLabel, '--f-body': t.fontBody, '--f-chip': t.chipFont,
    '--f-play': t.playFont, '--f-logo': t.logoFont, '--f-h2': t.h2Font,
    '--w-display': t.displayWeight, '--w-h2': t.h2Weight, '--w-label': t.labelWeight, '--w-badge': t.badgeWeight,
    '--w-play': t.playWeight, '--w-logo': t.logoWeight,
    '--fs-badge': t.badgeSize, '--fs-lang': t.langSize, '--fs-logo': t.logoSize, '--fs-h1': t.h1Size, '--fs-h1-desk': t.h1Desk,
    '--fs-h2': t.h2Size, '--fs-kicker': t.kickerSize, '--fs-play': t.playSize, '--fs-p': t.pSize,
    '--fs-card-title': t.cardTitleSize, '--fs-ad': t.adSize,
    '--radius': t.radius, '--btn-radius': t.btnRadius, '--chip-radius': t.chipRadius, '--badge-radius': t.badgeRadius,
    '--thumb-radius': parseInt(t.radius, 10) > 12 ? '12px' : t.radius,
    '--btn-clip': t.btnClip, '--chip-skew': t.chipSkew, '--badge-skew': t.badgeSkew,
    '--card-shadow': t.cardShadow, '--btn-shadow': t.btnShadow, '--logo-shadow': t.logoShadow,
    '--upper': t.upper, '--chip-case': t.chipCase, '--logo-case': t.logoCase,
    '--logo-track': t.logoTrack, '--track': t.track, '--label-track': t.labelTrack,
    '--logo-sep': q(t.logoSep), '--badge-text': q(t.badge), '--h2-prefix': q(t.h2Prefix),
    '--glyph-a': t.glyphA, '--glyph-b': t.glyphB, '--glyph-div': t.glyphDiv,
    'color-scheme': t.scheme,
  };
  t.tiles.forEach(([bg, fg], i) => { v[`--tile${i + 1}-bg`] = bg; v[`--tile${i + 1}-fg`] = fg; });
  t.origs.forEach(([bg, fg], i) => { v[`--orig${i + 1}-bg`] = bg; v[`--orig${i + 1}-fg`] = fg; });
  return Object.entries(v).map(([k, val]) => `  ${k}: ${val};`).join('\n');
}

let css = `/* GENERATED by scripts/gen-skins.mjs from src/config/skins.mjs — do not edit by hand. */\n\n`;
for (const t of SKINS) {
  const sel = t.id === DEFAULT_SKIN ? `:root, html[data-skin="${t.id}"]` : `html[data-skin="${t.id}"]`;
  css += `${sel} {\n${vars(t)}\n}\n\n`;
}

// Per-skin details: hero art variant and play-button label style.
css += `.hero-v { display: none; }\n.pl-press, .pl-term { display: none; }\n`;
const def = SKINS.find((s) => s.id === DEFAULT_SKIN);
css += `:root:not([data-skin]) .hero-v--${def.hero} { display: block; }\n`;
for (const t of SKINS) {
  css += `html[data-skin="${t.id}"] .hero-v--${t.hero} { display: block; }\n`;
  if (t.playStyle !== 'default') {
    css += `html[data-skin="${t.id}"] .pl-default { display: none; }\nhtml[data-skin="${t.id}"] .pl-${t.playStyle} { display: inline; }\n`;
  }
}
const unknown = HERO_VARIANTS.filter((v) => !SKINS.some((s) => s.hero === v));
if (unknown.length) css += `/* unused hero variants: ${unknown.join(', ')} */\n`;

mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/skins.css', css);

// Small JSON for the picker and the no-flash script.
const meta = SKINS.map((t) => ({ id: t.id, name: t.name, bg: t.bg, surface: t.surface, accent: t.accent, accent2: t.accent2, text: t.text, scheme: t.scheme }));
writeFileSync('src/config/skins-meta.json', JSON.stringify(meta, null, 2) + '\n');
console.log(`skins.css: ${SKINS.length} skins`);
