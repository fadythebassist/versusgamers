// Path segments per language.
const SEG = {
  en: { category: 'category', game: 'game', originals: 'originals', search: 'search', favorites: 'favorites', recent: 'recent', about: 'about', contact: 'contact', privacy: 'privacy', terms: 'terms' },
  fr: { category: 'categorie', game: 'jeu', originals: 'originaux', search: 'recherche', favorites: 'favoris', recent: 'recents', about: 'a-propos', contact: 'contact', privacy: 'confidentialite', terms: 'conditions' },
} as const;
export type PageKey = keyof (typeof SEG)['en'];

export const path = {
  home: (l: Lang) => `/${l}/`,
  page: (l: Lang, p: PageKey) => `/${l}/${SEG[l][p]}/`,
  category: (l: Lang, key: string) => {
    const c = CATEGORIES.find((x) => x.key === key)!;
    return `/${l}/${SEG[l].category}/${c.slug[l]}/`;
  },
  game: (l: Lang, slug: string) => `/${l}/${SEG[l].game}/${slug}/`,
  original: (l: Lang, slug: string) => `/${l}/${SEG[l].originals}/${slug}/`,
};

export const other = (l: Lang): Lang => (l === 'en' ? 'fr' : 'en');

