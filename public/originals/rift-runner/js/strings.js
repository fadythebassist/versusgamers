  function detectLang(search, navLang, saved) {
    var m = /[?&]lang=(fr|en)\b/i.exec(search || '');
    if (m) return { lang: m[1].toLowerCase(), fromUrl: true };
    if (saved === 'fr' || saved === 'en') return { lang: saved, fromUrl: false };
    return { lang: /^fr/i.test(navLang || '') ? 'fr' : 'en', fromUrl: false };
  }

  function setLang(l) {
    lang = l === 'fr' ? 'fr' : 'en';
    try { nf = new Intl.NumberFormat(lang === 'fr' ? 'fr-CA' : 'en-CA'); } catch (e) { nf = null; }
  }

  function fmt(n) { n = Math.floor(n); return nf ? nf.format(n) : String(n); }
  function fmtDec(n) { var s = String(n); return lang === 'fr' ? s.replace('.', ',') : s; }

  function t(key, params) {
    var str = (S[lang] && S[lang][key]);
    if (str == null) str = S.en[key];
    if (str == null) return key;
    if (params) {
      for (var k in params) if (Object.prototype.hasOwnProperty.call(params, k)) str = str.split('{' + k + '}').join(String(params[k]));
    }
    return str;
  }

